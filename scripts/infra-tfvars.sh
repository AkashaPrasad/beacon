#!/usr/bin/env bash
# Generates infra/terraform/terraform.tfvars (git-ignored) from secrets.env plus the
# current public IP (admin_cidr). Safe to re-run; rerun + apply when your IP changes.
#   scripts/infra-tfvars.sh            # admin_cidr = $(scripts/my-ip.sh)
#   ADMIN_CIDR=1.2.3.4/32 scripts/infra-tfvars.sh
set -euo pipefail
. "$(dirname "$0")/lib/env.sh"

load_secrets
require_vars AWS_PROFILE AWS_REGION SSH_PUBLIC_KEY SSH_PRIVATE_KEY_PATH GITHUB_REPO

admin_cidr=${ADMIN_CIDR:-$("$BEACON_ROOT/scripts/my-ip.sh")}

# HCL string escape: \ " ${ %{
hcl() {
  local s=$1
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  s=${s//\$\{/\$\$\{}
  s=${s//%\{/%%\{}
  printf '"%s"' "$s"
}

out="$TF_DIR/terraform.tfvars"
umask 077
{
  printf '# Generated by scripts/infra-tfvars.sh from secrets.env. Git-ignored. Do not edit.\n'
  printf 'aws_profile             = %s\n' "$(hcl "$AWS_PROFILE")"
  printf 'aws_region              = %s\n' "$(hcl "$AWS_REGION")"
  printf 'github_repo             = %s\n' "$(hcl "$GITHUB_REPO")"
  printf 'app_instance_type       = %s\n' "$(hcl "${AWS_INSTANCE_TYPE:-t4g.small}")"
  printf 'firecrawl_instance_type = %s\n' "$(hcl "${FIRECRAWL_INSTANCE_TYPE:-t4g.large}")"
  printf 'ssh_public_key          = %s\n' "$(hcl "$SSH_PUBLIC_KEY")"
  printf 'ssh_private_key_path    = %s\n' "$(hcl "$SSH_PRIVATE_KEY_PATH")"
  printf 'admin_cidr              = %s\n' "$(hcl "$admin_cidr")"
  # Optional overrides: set them in secrets.env, never by editing this file.
  [ -n "${APP_VOLUME_SIZE:-}" ] && printf 'app_volume_size         = %d\n' "$APP_VOLUME_SIZE"
  [ -n "${FIRECRAWL_VOLUME_SIZE:-}" ] && printf 'firecrawl_volume_size   = %d\n' "$FIRECRAWL_VOLUME_SIZE"
  [ -n "${FIRECRAWL_GIT_REF:-}" ] && printf 'firecrawl_git_ref       = %s\n' "$(hcl "$FIRECRAWL_GIT_REF")"
  [ -n "${FIRECRAWL_IMAGE_TAG:-}" ] && printf 'firecrawl_image_tag     = %s\n' "$(hcl "$FIRECRAWL_IMAGE_TAG")"
  [ -n "${CPU_CREDITS:-}" ] && printf 'cpu_credits             = %s\n' "$(hcl "$CPU_CREDITS")"
  true
} >"$out"
chmod 600 "$out"
info "wrote $out (admin_cidr=$admin_cidr)"
