/** Fixed clock: Tuesday 27 Oct 2026, 12:00 IST. */
export const FIXTURE_NOW = new Date('2026-10-27T06:30:00.000Z');

const daysFromNow = (days: number) => new Date(FIXTURE_NOW.getTime() + days * DAY_MS);
/** End of a day in IST (23:59:59.999 +05:30) `days` from FIXTURE_NOW. */
const istEndOfDay = (days: number) => {
  const d = daysFromNow(days);
  const ist = new Date(d.getTime() + 5.5 * 3_600_000);
  return new Date(
    Date.UTC(ist.getUTCFullYear(), ist.getUTCMonth(), ist.getUTCDate(), 23, 59, 59, 999) -
      5.5 * 3_600_000,
  );
};

