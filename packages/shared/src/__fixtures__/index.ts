// ── Listings ─────────────────────────────────────────────────────────────────

type ListingSeed = Omit<
  ListingInput,
  'canonicalKey' | 'contentHash' | 'firstSeenAt' | 'lastSeenAt' | 'roleFamily'
> & { firstSeenAt?: Date; lastSeenAt?: Date };

function build(seed: ListingSeed, ghostContext: Parameters<typeof ghostRisk>[1] = {}): Listing {
  const postedAt = seed.postedAt instanceof Date ? seed.postedAt : null;
  const firstSeenAt = seed.firstSeenAt ?? postedAt ?? FIXTURE_NOW;
  const lastSeenAt = seed.lastSeenAt ?? FIXTURE_NOW;
  const descriptionMd = seed.descriptionMd ?? '';
  const draft = {
    ...seed,
    firstSeenAt,
    lastSeenAt,
    canonicalKey: canonicalKey({
      company: seed.company,
      title: seed.title,
      location: seed.location ?? [],
      remote: seed.remote ?? 'unknown',
    }),
    contentHash: contentHash(descriptionMd),
    roleFamily: classifyRole(seed.title)?.family ?? null,
    ghostRisk: ghostRisk(
      { postedAt, firstSeenAt, lastSeenAt, title: seed.title, descriptionMd },
      { now: FIXTURE_NOW, ...ghostContext },
    ),
  };
  return listingSchema.parse(draft);
}

